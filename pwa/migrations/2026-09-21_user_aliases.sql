-- Self-chosen leaderboard aliases (2026-09-21): a player may pick a three-word
-- pseudonym for the public /leaderboard, out of three fixed lists.
--
-- New tables only — nothing existing changes shape, and NO user is backfilled:
-- an account without a user_aliases row keeps rendering exactly as it did
-- (Anonymous on /leaderboard). Idempotent, and the marked block below is
-- generated from shared/alias-words.js by scripts/gen-alias-seed.mjs, so a
-- fresh database (schema.sql) and the live one hold the same vocabulary.
--
-- Apply to the live D1 with:
--   cd pwa && npx wrangler d1 execute tsumego-reports --remote \
--       --file=migrations/2026-09-21_user_aliases.sql
CREATE TABLE IF NOT EXISTS alias_adjectives (word TEXT PRIMARY KEY);
CREATE TABLE IF NOT EXISTS alias_colors (word TEXT PRIMARY KEY);
CREATE TABLE IF NOT EXISTS alias_animals (word TEXT PRIMARY KEY);

-- The chosen triplet, stored as the ENGLISH words. English is the identity:
-- the UNIQUE index below is on these three columns, so translating the display
-- can never create or free a claim. There is deliberately no foreign key to the
-- word tables — shrinking a list must not rewrite or orphan an existing alias,
-- and composeAlias falls back to the stored English for a word no longer held.
--
-- user_id is the primary key because an account has exactly ONE alias, and
-- re-picking REPLACES it. Clearing the row is how a player goes back to
-- Anonymous, and the freed triplet becomes claimable by someone else.
--
-- This table is not pruned. The `leaderboard` table is deleted and rebuilt
-- weekly, and the alias is a durable choice rather than a rebuildable estimate.
CREATE TABLE IF NOT EXISTS user_aliases (
    user_id    TEXT PRIMARY KEY,
    adjective  TEXT NOT NULL,
    color      TEXT NOT NULL,
    animal     TEXT NOT NULL,
    created_at TEXT NOT NULL,
    updated_at TEXT NOT NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS idx_user_aliases_triplet
    ON user_aliases(adjective, color, animal);

