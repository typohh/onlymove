/**
 * Resolves the active UI language to one of the supported codes
 * ('zh' | 'ja' | 'ko' | 'en'). Single source of truth for getTerm and
 * localizedMotif.
 */
export function getLang() {
  const lang = navigator.language || 'en';
  if (lang.startsWith('zh')) return 'zh';
  if (lang.startsWith('ja')) return 'ja';
  if (lang.startsWith('ko')) return 'ko';
  return 'en';
}

/**
 * Localized motif label for a labels.components entry. Falls back to the
 * canonical English `positive` string when no translation exists for the
 * active language. Used by the review-mode motif bubble and the stats page.
 */
export function localizedMotif(component, side = 'positive') {
  if (!component) return null;
  const lang = getLang();
  // Axes are BIPOLAR (labels.json v4): either tail may carry a named motif,
  // and some axes name only one side (the other stays null → caller skips).
  const i18n = side === 'negative' ? component.negative_i18n : component.positive_i18n;
  const text = side === 'negative' ? component.negative : component.positive;
  return (i18n && i18n[lang]) || text || null;
}

export function getTerm(key, params) {
  const langDb = localization[getLang()];
  let term = (langDb && key in langDb) ? langDb[key] : localization.en[key];

  // Optional `{name}` interpolation: getTerm('rankUpTo', { rank }) replaces
  // each `{rank}` placeholder. Saves the chained `.replace('{x}', …)` calls
  // scattered across callers. Values are coerced to string; missing keys are
  // left as-is so a typo surfaces visibly rather than printing "undefined".
  if (params && typeof term === 'string') {
    term = term.replace(/\{(\w+)\}/g, (match, name) =>
      (name in params ? String(params[name]) : match));
  }
  return term;
}

export function getDescriptiveRank(rank) {
  // Ranks extend past the labelled 30k..9d ladder in both directions (the
  // unattempted hard tail runs above it, problems easier than M's weakest knot
  // below it), and the kyu/dan formula keeps working for any band, so nothing
  // here clamps: -31 -> "31 kyu", 9 -> "10 dan". The band comes from the shared
  // rankBand so this can't drift from rankToLabel; only the kyu/dan WORDING is
  // localized here, which is why this stays out of shared/rank-math.js.
  const band = rankBand(rank);
  const kyuTerm = getTerm('kyu');
  const danTerm = getTerm('dan');
  return (band < 0) ? `${-band} ${kyuTerm}` : `${band + 1} ${danTerm}`;
}