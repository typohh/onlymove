// pwa/scripts/gen-alias-seed.mjs
//
// Seeds the three alias word tables from shared/alias-words.js, the single
// source for the vocabulary. The tables are what the Worker validates a
// submitted triplet against, so they must hold exactly the words the client
// offers — this script is the mechanism that keeps the two from drifting.
//
//   node scripts/gen-alias-seed.mjs            # print the SQL block
//   node scripts/gen-alias-seed.mjs --write    # rewrite the marked blocks
//   node scripts/gen-alias-seed.mjs --check    # fail if a marked block differs
//
// The generated block lives between `-- >>> alias-seed` and `-- <<< alias-seed`
// markers in schema.sql (fresh databases) and in the migration that adds the
// tables to the live D1. Run --write after ANY edit to the word lists, commit
// the result, and let --check (or a reviewer) catch a missed regeneration.
//
// The block SYNCS each table to its list: it inserts every word, then PRUNES any
// word the list no longer holds, so the table and the module cannot disagree in
// either direction. Pruning is safe and deliberate — `user_aliases` has NO
// foreign key to these tables and `composeAlias` falls back to the stored English
// for a word the module no longer carries, so a retired word's alias still
// renders; what pruning removes is only the ability to newly CLAIM that word.
// Without it, a word deleted here would stay legal in D1 forever while the
// picker (which reads the module) stopped offering it.
//
// INSERT OR IGNORE, never a plain INSERT: rerunning schema.sql against the live
// D1 is routine, and a seed line that throws on the second run would make the
// schema script non-idempotent.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { ALIAS_ADJECTIVES, ALIAS_COLORS, ALIAS_ANIMALS } from '../shared/alias-words.js';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const PWA = path.join(HERE, '..');

const START = '-- >>> alias-seed';
const END = '-- <<< alias-seed';

const TARGETS = [
    path.join(PWA, 'schema.sql'),
    path.join(PWA, 'migrations', '2026-09-21_user_aliases.sql'),
];

const quote = (s) => `'${String(s).replace(/'/g, "''")}'`;

// Wrap a value list six per line so a long list stays readable in the diff.
// `tail` closes the statement — `);` for the NOT IN list, `;` for the VALUES
// tuples, whose own closing paren is part of each value.
function wrap(values, tail) {
    const lines = [];
    for (let i = 0; i < values.length; i += 6) {
        lines.push('    ' + values.slice(i, i + 6).join(', '));
    }
    return lines.map((l, i) => (i === lines.length - 1 ? l + tail : l + ',')).join('\n');
}

// One prune + one insert per table, both idempotent.
function syncTable(table, entries) {
    const remove = `DELETE FROM ${table} WHERE word NOT IN (\n${wrap(entries.map((w) => quote(w.en)), ');')}`;
    const insert = `INSERT OR IGNORE INTO ${table} (word) VALUES\n${wrap(entries.map((w) => `(${quote(w.en)})`), ';')}`;
    return remove + '\n' + insert;
}

function generate() {
    const body = [
        START + ' (generated by pwa/scripts/gen-alias-seed.mjs — do not edit by hand)',
        syncTable('alias_adjectives', ALIAS_ADJECTIVES),
        syncTable('alias_colors', ALIAS_COLORS),
        syncTable('alias_animals', ALIAS_ANIMALS),
        END,
    ].join('\n');
    return body;
}

function markedBlock(text) {
    const start = text.indexOf(START);
    const end = text.indexOf(END);
    if (start === -1 || end === -1 || end < start) return null;
    return text.slice(start, end + END.length);
}

function apply(text, block) {
    const existing = markedBlock(text);
    if (existing === null) return null;
    return text.slice(0, text.indexOf(START)) + block + text.slice(text.indexOf(END) + END.length);
}

const args = process.argv.slice(2);
const block = generate();

if (args.includes('--check')) {
    let bad = 0;
    for (const file of TARGETS) {
        let text;
        try { text = fs.readFileSync(file, 'utf-8'); } catch { console.error(`missing: ${file}`); bad++; continue; }
        const current = markedBlock(text);
        if (current === null) { console.error(`no alias-seed markers in ${file}`); bad++; continue; }
        if (current !== block) { console.error(`stale alias-seed block in ${file} — run --write`); bad++; }
    }
    if (bad) process.exit(1);
    console.log('alias seed blocks match shared/alias-words.js');
} else if (args.includes('--write')) {
    for (const file of TARGETS) {
        const text = fs.readFileSync(file, 'utf-8');
        const next = apply(text, block);
        if (next === null) {
            console.error(`no alias-seed markers in ${file} — add them before running --write`);
            process.exit(1);
        }
        fs.writeFileSync(file, next);
        console.log(`updated ${path.relative(PWA, file)}`);
    }
} else {
    console.log(block);
}
