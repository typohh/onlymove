"""Apply the solution-line audit to the corpus: remove the broken, restore the sound.

The sets come from the TE marks written by auxiliary/mark_recommended_variations.py.
A problem is BROKEN when either:

  a) its answer carries no root mark -- the answer does not resolve to a win
  b) SOME incorrect first move resolves, and every outcome it resolves to is a
     WIN for black -- that move is not actually refuted

(b) is judged per move. A problem with one refuted move leading to both a win
and a loss, and a second leading only to wins, is rejected on the second.

Live problems that are broken move to tsumegos/broken/. Quarantined problems
that are sound move back to tsumegos/ -- both earlier purges removed problems
for this same question (`eed2b88021`, `4f31c47b27`) using weaker instruments,
so their quarantines are re-decided here rather than trusted.

ARTIFACTS. Only what must move to keep the corpus self-consistent:

  activations/<size>/<id>.npz   MUST leave with a removed problem. It is not
        optional bookkeeping: cache_rating_features asserts the activation set
        is a SUBSET of the corpus and aborts otherwise, and correct_ids is
        derived from that listing, so an orphan silently promotes a problem
        that no longer exists into the rated set.
  axes/per_cell/<size>/<id>.npz moves with it, and is regenerated by build_axes.

Restored problems get their activations back from the loser backup where it has
them. Where it does not, the file is simply absent: corpus > activations is the
normal resumable state, and extract_activations fills it on the next run.
Restored bot attempt rows are NOT reconstructed here -- benchmark_bots skips ids
its attempt files already cover, so a plain re-run fills exactly the gap.

Attempt rows for REMOVED problems are left in place: they are keyed by tid and
simply never looked up once the id leaves correct_ids.

USAGE
    ./.venv/bin/python3 auxiliary/apply_solution_line_surgery.py --sets SETS.tsv
    ./.venv/bin/python3 auxiliary/apply_solution_line_surgery.py --sets SETS.tsv --apply
"""
import argparse
import os
import shutil
import sys

PROJECT_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
if PROJECT_ROOT not in sys.path:
    sys.path.append(PROJECT_ROOT)

REMOVED_BACKUP = os.path.join(PROJECT_ROOT, 'surgery', 'removed_2026-08-09')
LOSER_BACKUP = os.path.join(PROJECT_ROOT, 'surgery', 'loser_backup')


def read_sets(path):
    remove, restore = [], []
    for i, line in enumerate(open(path)):
        if i == 0:
            continue
        p = line.rstrip('\n').split('\t')
        where, size, tid, broken = p[0], p[1], p[2], p[7]
        if where == 'live' and broken == '1':
            remove.append((size, tid))
        elif where == 'quarantine' and broken == '0':
            restore.append((size, tid))
    return remove, restore


def move(src, dst, apply):
    if not os.path.exists(src):
        return False
    if apply:
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        shutil.move(src, dst)
    return True


def copy(src, dst, apply):
    if not os.path.exists(src):
        return False
    if apply:
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        shutil.copy2(src, dst)
    return True


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--sets', required=True)
    ap.add_argument('--apply', action='store_true')
    args = ap.parse_args()

    remove, restore = read_sets(args.sets)
    print(f"remove {len(remove)} live, restore {len(restore)} quarantined")

    counts = dict(sgf_out=0, npz_out=0, cell_out=0,
                  sgf_back=0, npz_back=0, npz_missing=0)

    for size, tid in remove:
        if move(f'{PROJECT_ROOT}/tsumegos/{size}/{tid}.sgf',
                f'{PROJECT_ROOT}/tsumegos/broken/{size}/{tid}.sgf', args.apply):
            counts['sgf_out'] += 1
        if move(f'{PROJECT_ROOT}/activations/{size}/{tid}.npz',
                f'{REMOVED_BACKUP}/activations/{size}/{tid}.npz', args.apply):
            counts['npz_out'] += 1
        if move(f'{PROJECT_ROOT}/axes/per_cell/{size}/{tid}.npz',
                f'{REMOVED_BACKUP}/per_cell/{size}/{tid}.npz', args.apply):
            counts['cell_out'] += 1

    for size, tid in restore:
        if move(f'{PROJECT_ROOT}/tsumegos/broken/{size}/{tid}.sgf',
                f'{PROJECT_ROOT}/tsumegos/{size}/{tid}.sgf', args.apply):
            counts['sgf_back'] += 1
        if copy(f'{LOSER_BACKUP}/activations/{size}/{tid}.npz',
                f'{PROJECT_ROOT}/activations/{size}/{tid}.npz', args.apply):
            counts['npz_back'] += 1
        else:
            counts['npz_missing'] += 1

    print(f"  SGFs quarantined            : {counts['sgf_out']}")
    print(f"  activations withdrawn       : {counts['npz_out']}")
    print(f"  per-cell embeddings withdrawn: {counts['cell_out']}")
    print(f"  SGFs restored               : {counts['sgf_back']}")
    print(f"  activations restored        : {counts['npz_back']}")
    print(f"  activations to re-extract   : {counts['npz_missing']}")

    if not args.apply:
        print("\ndry run -- nothing moved. Re-run with --apply.")
        return

    # The invariant the next cache build asserts, checked here while the cause
    # is still obvious rather than three steps downstream.
    for size in (9, 13):
        with os.scandir(f'{PROJECT_ROOT}/tsumegos/{size}') as it:
            corpus = {e.name[:-4] for e in it if e.name.endswith('.sgf')}
        with os.scandir(f'{PROJECT_ROOT}/activations/{size}') as it:
            act = {e.name[:-4] for e in it if e.name.endswith('.npz')}
        orphans = act - corpus
        print(f"  {size}x{size}: corpus={len(corpus)} activations={len(act)} "
              f"orphan_npz={len(orphans)} missing_npz={len(corpus - act)}")
        if orphans:
            raise SystemExit(f"ORPHAN ACTIVATIONS on {size}x{size}: "
                             f"{sorted(orphans)[:5]} -- cache build would abort")


if __name__ == '__main__':
    main()
